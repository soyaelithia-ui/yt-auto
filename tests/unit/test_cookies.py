def test_parse_cookies_empty_or_invalid_file(tmp_path):
    empty_file = tmp_path / "empty.json"
    empty_file.write_text("", encoding="utf-8")
    with pytest.raises(ValueError, match="Cookies file is empty"):
        parse_cookies_file(empty_file)

    invalid_json = tmp_path / "invalid.json"
    invalid_json.write_text("{ \"not\": \"a list\" }", encoding="utf-8")
    with pytest.raises(ValueError, match="Invalid cookies format"):
        parse_cookies_file(invalid_json)


