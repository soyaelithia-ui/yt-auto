def test_validate_youtube_session_cookies_healthy():
    future_time = time.time() + 86400 * 20
    cookies = [
        {"name": "LOGIN_INFO", "value": "xyz", "expires": future_time},
        {"name": "SID", "value": "sid_val", "expires": future_time},
        {"name": "__Secure-1PSID", "value": "1psid_val", "expires": future_time},
        {"name": "HSID", "value": "hsid_val", "expires": future_time},
        {"name": "SSID", "value": "ssid_val", "expires": future_time},
        {"name": "SAPISID", "value": "sapisid_val", "expires": future_time},
    ]

    result = validate_youtube_session_cookies(cookies)
    assert result.status == SessionStatus.HEALTHY
    assert result.days_left is not None and result.days_left > 19
    assert len(result.missing_tokens) == 0
    assert "activas" in result.detail.lower()


