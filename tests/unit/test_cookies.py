def test_parse_json_cookies_array(tmp_path):
    cookie_file = tmp_path / "cookies.json"
    sample = [
        {
            "name": "LOGIN_INFO",
            "value": "AFmmF2kwRQ...token",
            "domain": ".youtube.com",
            "path": "/",
            "expires": time.time() + 86400 * 30,
            "httpOnly": True,
            "secure": True,
            "sameSite": "None",
        },
        {
            "name": "SID",
            "value": "sid_sample_value",
            "domain": ".google.com",
            "path": "/",
            "expirationDate": time.time() + 86400 * 30,
            "httpOnly": False,
            "secure": True,
            "sameSite": "lax",
        },
    ]
    cookie_file.write_text(json.dumps(sample), encoding="utf-8")

    cookies = parse_cookies_file(cookie_file)
    assert len(cookies) == 2
    assert cookies[0]["name"] == "LOGIN_INFO"
    assert cookies[0]["value"] == "AFmmF2kwRQ...token"
    assert cookies[0]["domain"] == ".youtube.com"
    assert cookies[0]["secure"] is True
    assert cookies[0]["httpOnly"] is True
    assert cookies[1]["name"] == "SID"
    assert cookies[1]["expires"] > time.time()


def test_parse_netscape_cookies_file(tmp_path):
    cookie_file = tmp_path / "cookies.txt"
    future_expiry = int(time.time() + 86400 * 15)
    content = f"""# Netscape HTTP Cookie File
# http://curl.haxx.se/rfc/cookie_spec.html
# This file was generated by yt-dlp

.youtube.com	TRUE	/	TRUE	{future_expiry}	LOGIN_INFO	netscape_login_token_val
.google.com	TRUE	/	TRUE	{future_expiry}	__Secure-1PSID	secure_1psid_val
.youtube.com	TRUE	/	FALSE	{future_expiry}	PREF	f4=4000000
"""
    cookie_file.write_text(content, encoding="utf-8")

    cookies = parse_cookies_file(cookie_file)
    assert len(cookies) == 3
    names = [c["name"] for c in cookies]
    assert "LOGIN_INFO" in names
    assert "__Secure-1PSID" in names
    assert "PREF" in names

    login_c = next(c for c in cookies if c["name"] == "LOGIN_INFO")
    assert login_c["value"] == "netscape_login_token_val"
    assert login_c["domain"] == ".youtube.com"
    assert login_c["secure"] is True
    assert login_c["expires"] == float(future_expiry)


